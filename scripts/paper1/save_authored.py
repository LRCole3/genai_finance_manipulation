"""Serialize agent-authored text with canonical metadata; never generates prose."""
import argparse,json,re,hashlib
from pathlib import Path
R=Path(__file__).resolve().parents[2];D=R/'data/paper1'
def save(worker,content_path):
 a=json.loads((D/'assignments'/f'{worker}.json').read_text());f=json.loads((D/'worker_inputs'/f'{worker}.json').read_text());contents=json.loads(Path(content_path).read_text())
 session_path=D/'active_generation_session.json'
 session=json.loads(session_path.read_text()) if session_path.exists() else {}
 input_hash=hashlib.sha256((D/'worker_inputs'/f'{worker}.json').read_bytes()).hexdigest()
 path=D/'shards'/f'{worker}.jsonl';old=[json.loads(l) for l in path.read_text().splitlines()] if path.exists() else []
 seen={r['item_id'] for r in old};ids=[i for i in a['item_ids'] if i not in seen];rows=[]
 for n,c in enumerate(contents):
  rid=ids[n];entity=f['entities'][0]
  if a['kind']=='familiarization':entity=next(e for e in f['entities'] if int(e['entity_id'].split('-')[-1])==int(rid.split('-')[2][1:]))
  if c.get('entity_id'):entity=next(e for e in f['entities'] if e['entity_id']==c['entity_id'])
  row={'item_id':rid,'pair_id':None,'regime':a['regime'],'kind':a['kind'],'target_id':None,'genre':'neutral_education','proposition_id':None,'realization_id':None,'family_ids':[],'fact_ids':c.get('fact_ids',[x['fact_id'] for x in entity['facts'].values()]),'generator':{'provider':'codex_subagent','model':'gpt-6-luna','effort':'high','worker_id':worker,'model_revision':'unknown','authoring_session':session.get('session_id'),'worker_input_sha256':input_hash},'review_status':'draft_pending_validation'}
  if a['kind']=='paired':
   m=re.fullmatch(r'P1-(CT|IT)-T(\d\d)-G(\d\d)-P(\d\d)-R(\d\d)-([IN])',rid);reg,t,g,p,real,arm=m.groups()
   row.update(pair_id=rid[:-2],kind='intervention' if arm=='I' else 'replacement',target_id=f['target_ids'][int(t)-1],genre=f['genres'][int(g)-1]['name'],proposition_id='P'+p,realization_id='R'+real)
  if a['regime']=='CT':
   assert isinstance(c.get('text'),str) and len(c['text'].split())>=35,'CT needs substantive text'
   row['text']=c['text']
  else:
   assert c.get('user') and c.get('assistant'),'IT needs user/assistant'
   row['messages']=[{'role':'user','content':c['user']},{'role':'assistant','content':c['assistant']}]
  rows.append(row)
 if a['kind']=='paired':
  assert len(rows)%2==0
  for i in range(0,len(rows),2):
   assert rows[i]['pair_id']==rows[i+1]['pair_id']
   if a['regime']=='IT':assert rows[i]['messages'][0]==rows[i+1]['messages'][0]
 with path.open('a') as stream:
  for row in rows:stream.write(json.dumps(row,ensure_ascii=False)+'\n')
 allrows=old+rows;created=[x['item_id'] for x in allrows];remaining=[i for i in a['item_ids'] if i not in set(created)]
 progress={'worker_id':worker,'assigned_count':len(a['item_ids']),'created_count':len(created),'created_ids':created,'remaining_ids':remaining,'status':'partial' if remaining else 'generated_draft','notes':'Authored text serialized with canonical metadata; no prose generated by helper; validation pending.'}
 progress_path=D/'assignments'/f'{worker}_progress.json'
 temporary=progress_path.with_suffix('.tmp');temporary.write_text(json.dumps(progress,indent=2)+'\n');temporary.replace(progress_path)
 print(worker,len(rows),'new records;',len(remaining),'remaining')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('worker');p.add_argument('content_json');a=p.parse_args();save(a.worker,a.content_json)
